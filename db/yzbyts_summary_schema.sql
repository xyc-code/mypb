-- “一支部一特色”年度总结表。
-- 正式环境执行前请先确认 DYN_D_YZBYTS 已包含 PARTY_ID、NF、D_DZZMC、D_HDZT、D_HDRWJJ。
CREATE TABLE DYN_YZBYTS_SUMMARY (
    ID VARCHAR2(50) NOT NULL,
    CREATED_BY VARCHAR2(50),
    CREATION_DATE DATE,
    LAST_UPDATED_BY VARCHAR2(50),
    LAST_UPDATE_DATE DATE,
    LAST_UPDATE_IP VARCHAR2(50),
    VERSION NUMBER(16),
    ORG_IDENTITY VARCHAR2(32),
    SUMMARY_YEAR VARCHAR2(4) NOT NULL,
    PARTY_ID VARCHAR2(50) NOT NULL,
    DECLARATION_ID VARCHAR2(50) NOT NULL,
    PARTY_NAME VARCHAR2(200),
    SOURCE_THEME VARCHAR2(1000),
    SOURCE_BACKGROUND CLOB,
    SOURCE_EXTRACTED_AT DATE,
    ACTIVITY_THEME VARCHAR2(1000),
    ACTIVITY_GOAL VARCHAR2(4000),
    ACTIVITY_BACKGROUND CLOB,
    WORK_THOUGHT CLOB,
    PRACTICE CLOB,
    ACHIEVEMENT CLOB,
    STATUS VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
    SUBMITTED_AT DATE,
    CONSTRAINT PK_DYN_YZBYTS_SUMMARY PRIMARY KEY (ID),
    CONSTRAINT UK_DYN_YZBYTS_SUMMARY UNIQUE (SUMMARY_YEAR, PARTY_ID)
);

CREATE TABLE DYN_YZBYTS_SUMMARY_FILE (
    ID VARCHAR2(50) NOT NULL,
    CREATED_BY VARCHAR2(50),
    CREATION_DATE DATE,
    LAST_UPDATED_BY VARCHAR2(50),
    LAST_UPDATE_DATE DATE,
    LAST_UPDATE_IP VARCHAR2(50),
    VERSION NUMBER(16),
    ORG_IDENTITY VARCHAR2(32),
    SUMMARY_ID VARCHAR2(50) NOT NULL,
    FILE_NAME VARCHAR2(500) NOT NULL,
    CONTENT_TYPE VARCHAR2(100),
    FILE_SIZE NUMBER(16),
    SORT_NO NUMBER(4),
    FILE_CONTENT BLOB NOT NULL,
    CONSTRAINT PK_DYN_YZBYTS_SUMMARY_FILE PRIMARY KEY (ID),
    CONSTRAINT FK_YZBYTS_SUMMARY_FILE FOREIGN KEY (SUMMARY_ID) REFERENCES DYN_YZBYTS_SUMMARY(ID)
);

