-- 日期字段应为 DATE 或 TIMESTAMP 系列；字符串日期不应直接套用本地建表定义。
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH
  FROM USER_TAB_COLUMNS
 WHERE (TABLE_NAME = 'DYN_TWSHYK' AND COLUMN_NAME = 'HYRQ')
    OR (TABLE_NAME = 'PARTY_ORGANIZATION' AND COLUMN_NAME = 'CREATION_DATE')
    OR (TABLE_NAME = 'DYN_YZBYTS_LCB' AND COLUMN_NAME = 'JHWCSJ')
    OR (TABLE_NAME = 'DYN_ZXGJZB' AND COLUMN_NAME = 'SJJD')
    OR (TABLE_NAME = 'DYN_ZZDR_INFO' AND COLUMN_NAME IN ('DATA_4', 'DATA_7'))
 ORDER BY TABLE_NAME, COLUMN_NAME;

-- 一特色需要已有考核开始月/日配置；应至少一条，且所有记录表达同一有效月日。
-- 本查询返回原值供核对，不为内网补写本地的 3 月 1 日配置。
SELECT KH_MONTH, KH_DAY, COUNT(*) AS ROW_COUNT
  FROM DYN_YZBYTSKHRQ GROUP BY KH_MONTH, KH_DAY;

-- 以下查询仅列出需要核对的来源记录，不自动删除/补值/跳过，也不增加业务规则。
-- 查询覆盖全源表；重复主表、缺日期是否影响本次计算，须结合已有组织范围和所选年度判断。
-- 不在当前计算范围内的历史记录、孤立子记录不应一律认定为部署阻断。
SELECT 'YZBYTS_INVALID_YEAR' AS CHECK_CODE, ID, PARTY_ID, NF
  FROM DYN_D_YZBYTS
 WHERE TRIM(NF) IS NULL OR NOT REGEXP_LIKE(TRIM(NF), '^[0-9]{4}$')
    OR TRIM(NF) IN ('0000', '9999');
SELECT 'YZBYTS_DUPLICATE_YEAR' AS CHECK_CODE, PARTY_ID, TRIM(NF) AS NF, COUNT(*) AS ROW_COUNT
  FROM DYN_D_YZBYTS GROUP BY PARTY_ID, TRIM(NF) HAVING COUNT(*) > 1;
SELECT 'YZBYTS_MISSING_DATE' AS CHECK_CODE, ID, FK_COL_ID
  FROM DYN_YZBYTS_LCB WHERE JHWCSJ IS NULL;
-- 主题党日实际接受1至9999的整数年份，SQL以Integer.toString(year)匹配NF。
-- 下列为年份查询一致性提示，例如0026会转成26却无法匹配原NF；26本身不是无效年份。
SELECT 'ZTDR_NONSTANDARD_YEAR' AS CHECK_CODE, ID, PARTY_ID, NF
  FROM DYN_ZTDR
 WHERE NVL(LENGTH(TRIM(NF)), 0) = 0
    OR NOT REGEXP_LIKE(TRIM(NF), '^[1-9][0-9]{0,3}$');
SELECT 'ZTDR_DUPLICATE_YEAR' AS CHECK_CODE, PARTY_ID, TRIM(NF) AS NF, COUNT(*) AS ROW_COUNT
  FROM DYN_ZTDR GROUP BY PARTY_ID, TRIM(NF) HAVING COUNT(*) > 1;
-- DATA_4为空不会抛异常，但该活动无法归属月份，按现有规则不算当月计划。
SELECT 'ZTDR_MISSING_PLAN_DATE' AS CHECK_CODE, ID, FK_CLO_ID
  FROM DYN_ZZDR_INFO WHERE DATA_4 IS NULL;
SELECT 'ZXGJ_INVALID_YEAR' AS CHECK_CODE, ID, PARTY_ID, BDBH
  FROM DYN_ZHUXINGJ
 WHERE TRIM(BDBH) IS NULL OR NOT REGEXP_LIKE(SUBSTR(TRIM(BDBH), 1, 4), '^[0-9]{4}$')
    OR SUBSTR(TRIM(BDBH), 1, 4) = '0000';
SELECT 'ZXGJ_MISSING_DATE' AS CHECK_CODE, ID, WJ FROM DYN_ZXGJZB WHERE SJJD IS NULL;

-- 没有组织域的组织无法被定时任务枚举。这是数据核对，不新增组织范围规则。
SELECT 'LEAGUE_MISSING_DOMAIN' AS CHECK_CODE, ID, LEAGUE_NAME AS ORG_NAME
  FROM LEAGUE_ORGANIZATION
 WHERE NVL(LENGTH(TRIM(ORG_IDENTITY)), 0) = 0 AND (PARENT_ID IS NULL OR PARENT_ID <> '-1');
SELECT 'PARTY_MISSING_DOMAIN' AS CHECK_CODE, ID, PARTY_NAME AS ORG_NAME
  FROM PARTY_ORGANIZATION WHERE NVL(LENGTH(TRIM(ORG_IDENTITY)), 0) = 0;

-- 第二部分：统一结果表安装后执行。首次安装前两表缺失属预期，先按发布说明建表。
SELECT ID, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, LAST_UPDATE_IP,
       VERSION, ORG_IDENTITY, CATEGORY_CODE, MODULE_CODE, MODULE_NAME, RULE_VERSION,
       ASSESS_ORG_ID, ASSESS_ORG_NAME, DEPT_ID, DEPT_NAME, ASSESS_YEAR, ASSESS_MONTH,
       RESULT_KIND, RESULT_SCORE, REASON_DETAIL
  FROM PB_ASSESS_MONTH_RESULT WHERE 1 = 0;
SELECT ID, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE, LAST_UPDATE_IP,
       VERSION, ORG_IDENTITY, RESULT_ID, DEPT_ID, DEPT_NAME
  FROM PB_ASSESS_RESULT_DEPT WHERE 1 = 0;
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, DATA_PRECISION, DATA_SCALE
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME IN ('PB_ASSESS_MONTH_RESULT', 'PB_ASSESS_RESULT_DEPT')
 ORDER BY TABLE_NAME, COLUMN_ID;
SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS
  FROM USER_CONSTRAINTS
 WHERE TABLE_NAME IN ('PB_ASSESS_MONTH_RESULT', 'PB_ASSESS_RESULT_DEPT')
 ORDER BY TABLE_NAME, CONSTRAINT_NAME;
SELECT TABLE_NAME, INDEX_NAME, COLUMN_NAME, COLUMN_POSITION
  FROM USER_IND_COLUMNS
 WHERE TABLE_NAME IN ('PB_ASSESS_MONTH_RESULT', 'PB_ASSESS_RESULT_DEPT')
 ORDER BY TABLE_NAME, INDEX_NAME, COLUMN_POSITION;

-- 旧单部门版本若已有数据，这里列出尚未迁移的历史归属；必须迁移已保存快照，
-- 不能以当前组织关联重新生成历史归属。首次全新安装应为空。
SELECT R.ID, R.MODULE_CODE, R.ASSESS_YEAR, R.ASSESS_MONTH, R.DEPT_ID, R.DEPT_NAME
  FROM PB_ASSESS_MONTH_RESULT R
 WHERE LENGTH(TRIM(REPLACE(REPLACE(R.DEPT_ID, ';', ''), ',', ''))) > 0
   AND NOT EXISTS (SELECT 1 FROM PB_ASSESS_RESULT_DEPT D
       WHERE D.ORG_IDENTITY = R.ORG_IDENTITY AND D.RESULT_ID = R.ID);

