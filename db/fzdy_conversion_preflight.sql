SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN ('DYN_FZDY', 'PARTY_MEMBER', 'SYS_USER', 'PARTY_ORGANIZATION', 'BPM_HIST_PROCINST')
ORDER BY TABLE_NAME, COLUMN_ID;

SELECT VIEW_CODE, TABLE_NAME, TYPE, COUNT(*) METHOD_COUNT
FROM SYS_DATA_PERMISSIONS_METHOD
WHERE UPPER(TABLE_NAME) = 'DYN_FZDY'
GROUP BY VIEW_CODE, TABLE_NAME, TYPE;

-- Multiple historical instances are deliberately rejected instead of guessing the current one.
SELECT P.FORMID_, COUNT(*) INSTANCE_COUNT
FROM BPM_HIST_PROCINST P JOIN DYN_FZDY F ON F.ID=P.FORMID_
GROUP BY P.FORMID_ HAVING COUNT(*) > 1;

SELECT P.STATE_, P.BUSINESSSTATE_, COUNT(*) RECORD_COUNT
FROM BPM_HIST_PROCINST P JOIN DYN_FZDY F ON F.ID=P.FORMID_
GROUP BY P.STATE_, P.BUSINESSSTATE_;

SELECT UPPER(TRIM(IDCARD)) IDCARD, COUNT(*) MEMBER_COUNT
FROM PARTY_MEMBER WHERE TRIM(IDCARD) IS NOT NULL
GROUP BY UPPER(TRIM(IDCARD)) HAVING COUNT(*) > 1;

SELECT COUNT(*) MISSING_IDCARD_COUNT FROM DYN_FZDY WHERE TRIM(SSZH) IS NULL;

SELECT XB, COUNT(*) RECORD_COUNT FROM DYN_FZDY GROUP BY XB;
SELECT WHCD, COUNT(*) RECORD_COUNT FROM DYN_FZDY GROUP BY WHCD;
