CREATE TABLE DYN_DYFSYZ (
    ID VARCHAR2(50) NOT NULL PRIMARY KEY,
    CREATED_BY VARCHAR2(50),
    CREATION_DATE DATE,
    LAST_UPDATED_BY VARCHAR2(50),
    LAST_UPDATE_DATE DATE,
    LAST_UPDATE_IP VARCHAR2(50),
    VERSION NUMBER(16),
    ORG_IDENTITY VARCHAR2(32),
    CREATED_DEPT VARCHAR2(50),
    EMPLOYEE_CODE VARCHAR2(100),
    MEMBER_ID VARCHAR2(50),
    MEMBER_NAME VARCHAR2(100),
    PARTY_ID VARCHAR2(50),
    RECEIVER_ORG_NAME VARCHAR2(300),
    PARTY_TYPE VARCHAR2(50),
    PARTY_TYPE_NAME VARCHAR2(50),
    MEETING_DATE DATE,
    MEETING_NAME VARCHAR2(300),
    PROBATION_START DATE,
    PROBATION_END DATE,
    REGULAR_DATE DATE,
    DOCUMENT_NO VARCHAR2(200),
    TITLE VARCHAR2(500),
    PROCESS_INSTANCE_ID VARCHAR2(50),
    SECRETARY_ID VARCHAR2(50),
    NOTICE_STATE VARCHAR2(20) DEFAULT 'draft',
    APPLIED_DATE DATE
);
CREATE UNIQUE INDEX UX_DYFSYZ_PROCESS ON DYN_DYFSYZ(PROCESS_INSTANCE_ID);
COMMENT ON TABLE DYN_DYFSYZ IS '党员发送阅知';
