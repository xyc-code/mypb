-- Department snapshots for a monthly result. Install after monthly_assessment_schema.sql.
CREATE TABLE PB_ASSESS_RESULT_DEPT (
    ID VARCHAR2(50) NOT NULL,
    CREATED_BY VARCHAR2(50),
    CREATION_DATE DATE,
    LAST_UPDATED_BY VARCHAR2(50),
    LAST_UPDATE_DATE DATE,
    LAST_UPDATE_IP VARCHAR2(50),
    VERSION NUMBER(16),
    ORG_IDENTITY VARCHAR2(32) NOT NULL,
    RESULT_ID VARCHAR2(50) NOT NULL,
    DEPT_ID VARCHAR2(50) NOT NULL,
    DEPT_NAME VARCHAR2(200),
    CONSTRAINT PK_PB_ASSESS_RESULT_DEPT PRIMARY KEY (ID),
    CONSTRAINT UK_PB_ASSESS_RESULT_DEPT UNIQUE (ORG_IDENTITY, RESULT_ID, DEPT_ID),
    CONSTRAINT FK_PB_ASSESS_RESULT_DEPT FOREIGN KEY (RESULT_ID)
        REFERENCES PB_ASSESS_MONTH_RESULT(ID) ON DELETE CASCADE
);
CREATE INDEX IX_PB_ASSESS_DEPT_LOOKUP ON PB_ASSESS_RESULT_DEPT
    (ORG_IDENTITY, DEPT_ID, RESULT_ID);
COMMENT ON TABLE PB_ASSESS_RESULT_DEPT IS '月度考核结果部门归属快照';
COMMENT ON COLUMN PB_ASSESS_RESULT_DEPT.ID IS 'ID';
COMMENT ON COLUMN PB_ASSESS_RESULT_DEPT.CREATED_BY IS 'CREATED_BY';
COMMENT ON COLUMN PB_ASSESS_RESULT_DEPT.CREATION_DATE IS 'CREATION_DATE';
COMMENT ON COLUMN PB_ASSESS_RESULT_DEPT.LAST_UPDATED_BY IS 'LAST_UPDATED_BY';
COMMENT ON COLUMN PB_ASSESS_RESULT_DEPT.LAST_UPDATE_DATE IS 'LAST_UPDATE_DATE';
COMMENT ON COLUMN PB_ASSESS_RESULT_DEPT.LAST_UPDATE_IP IS 'LAST_UPDATE_IP';
COMMENT ON COLUMN PB_ASSESS_RESULT_DEPT.VERSION IS 'VERSION';
COMMENT ON COLUMN PB_ASSESS_RESULT_DEPT.ORG_IDENTITY IS 'ORG_IDENTITY';
COMMENT ON COLUMN PB_ASSESS_RESULT_DEPT.RESULT_ID IS '月度考核结果ID';
COMMENT ON COLUMN PB_ASSESS_RESULT_DEPT.DEPT_ID IS '部门ID';
COMMENT ON COLUMN PB_ASSESS_RESULT_DEPT.DEPT_NAME IS '部门名称快照';
