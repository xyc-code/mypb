CREATE TABLE DYN_SJ_COMP_BATCH (
 ID VARCHAR2(50) NOT NULL PRIMARY KEY,
 CREATED_BY VARCHAR2(50),
 CREATION_DATE DATE,
 LAST_UPDATED_BY VARCHAR2(50),
 LAST_UPDATE_DATE DATE,
 LAST_UPDATE_IP VARCHAR2(50),
 VERSION NUMBER(16),
 ORG_IDENTITY VARCHAR2(32),
 CREATED_DEPT VARCHAR2(50),
 BATCH_NAME VARCHAR2(200) NOT NULL,
 EVAL_YEAR NUMBER(4) NOT NULL,
 EVAL_DATE DATE NOT NULL,
 RULE_VERSION VARCHAR2(30) NOT NULL
);
CREATE TABLE DYN_SJ_COMP_SCORE (
 ID VARCHAR2(50) NOT NULL PRIMARY KEY,
 CREATED_BY VARCHAR2(50),
 CREATION_DATE DATE,
 LAST_UPDATED_BY VARCHAR2(50),
 LAST_UPDATE_DATE DATE,
 LAST_UPDATE_IP VARCHAR2(50),
 VERSION NUMBER(16),
 ORG_IDENTITY VARCHAR2(32),
 CREATED_DEPT VARCHAR2(50),
 BATCH_ID VARCHAR2(50) NOT NULL REFERENCES DYN_SJ_COMP_BATCH(ID),
 USER_ID VARCHAR2(50) NOT NULL,
 PARTY_ID VARCHAR2(50) NOT NULL,
 EMPLOYEE_CODE VARCHAR2(100),
 MEMBER_NAME VARCHAR2(100),
 PARTY_NAME VARCHAR2(300),
 POST_NAME VARCHAR2(100),
 THEORY_SCORE NUMBER(5,2),
 BUSINESS_SCORE NUMBER(5,2),
 INTERVIEW_SCORE NUMBER(5,2),
 SATISFACTION_SCORE NUMBER(5,2),
 ACTIVITY_SCORE NUMBER(5,2),
 RULE_VERSION VARCHAR2(30) NOT NULL,
 CONSTRAINT UX_SJ_COMP_PERSON UNIQUE(BATCH_ID,USER_ID,PARTY_ID),
 CONSTRAINT CK_COMP_THEORY CHECK(THEORY_SCORE BETWEEN 0 AND 100),
 CONSTRAINT CK_COMP_BUSINESS CHECK(BUSINESS_SCORE BETWEEN 0 AND 100),
 CONSTRAINT CK_COMP_INTERVIEW CHECK(INTERVIEW_SCORE BETWEEN 0 AND 100),
 CONSTRAINT CK_COMP_SATISFACTION CHECK(SATISFACTION_SCORE BETWEEN 0 AND 100),
 CONSTRAINT CK_COMP_ACTIVITY CHECK(ACTIVITY_SCORE BETWEEN 0 AND 100)
);
CREATE INDEX IX_SJ_COMP_PARTY ON DYN_SJ_COMP_SCORE(PARTY_ID,BATCH_ID);
COMMENT ON TABLE DYN_SJ_COMP_BATCH IS '书记胜任力测评批次';
COMMENT ON TABLE DYN_SJ_COMP_SCORE IS '书记胜任力人员成绩';

