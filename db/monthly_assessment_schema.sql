-- Run once in the PB application schema (Dameng / Oracle compatible).
CREATE TABLE PB_ASSESS_MONTH_RESULT (
    ID VARCHAR2(50) NOT NULL,
    CREATED_BY VARCHAR2(50),
    CREATION_DATE DATE,
    LAST_UPDATED_BY VARCHAR2(50),
    LAST_UPDATE_DATE DATE,
    LAST_UPDATE_IP VARCHAR2(50),
    VERSION NUMBER(16),
    ORG_IDENTITY VARCHAR2(32) NOT NULL,
    CATEGORY_CODE VARCHAR2(20),
    MODULE_CODE VARCHAR2(100) NOT NULL,
    MODULE_NAME VARCHAR2(200),
    RULE_VERSION VARCHAR2(50),
    ASSESS_ORG_ID VARCHAR2(50) NOT NULL,
    ASSESS_ORG_NAME VARCHAR2(200),
    DEPT_ID VARCHAR2(50),
    DEPT_NAME VARCHAR2(200),
    ASSESS_YEAR NUMBER(4) NOT NULL,
    ASSESS_MONTH NUMBER(2) NOT NULL,
    RESULT_KIND VARCHAR2(20),
    RESULT_SCORE NUMBER(12,4),
    REASON_DETAIL CLOB,
    CONSTRAINT PK_PB_ASSESS_MONTH PRIMARY KEY (ID),
    CONSTRAINT UK_PB_ASSESS_MONTH UNIQUE
        (ORG_IDENTITY, MODULE_CODE, ASSESS_ORG_ID, ASSESS_YEAR, ASSESS_MONTH)
);
CREATE INDEX IX_PB_ASSESS_MONTH_DEPT ON PB_ASSESS_MONTH_RESULT
    (ORG_IDENTITY, ASSESS_YEAR, ASSESS_MONTH, DEPT_ID);
COMMENT ON TABLE PB_ASSESS_MONTH_RESULT IS '统一月度考核结果';
COMMENT ON COLUMN PB_ASSESS_MONTH_RESULT.ID IS 'ID';
COMMENT ON COLUMN PB_ASSESS_MONTH_RESULT.CREATED_BY IS 'CREATED_BY';
COMMENT ON COLUMN PB_ASSESS_MONTH_RESULT.CREATION_DATE IS 'CREATION_DATE';
COMMENT ON COLUMN PB_ASSESS_MONTH_RESULT.LAST_UPDATED_BY IS 'LAST_UPDATED_BY';
COMMENT ON COLUMN PB_ASSESS_MONTH_RESULT.LAST_UPDATE_DATE IS 'LAST_UPDATE_DATE';
COMMENT ON COLUMN PB_ASSESS_MONTH_RESULT.LAST_UPDATE_IP IS 'LAST_UPDATE_IP';
COMMENT ON COLUMN PB_ASSESS_MONTH_RESULT.VERSION IS 'VERSION';
COMMENT ON COLUMN PB_ASSESS_MONTH_RESULT.ORG_IDENTITY IS 'ORG_IDENTITY';
COMMENT ON COLUMN PB_ASSESS_MONTH_RESULT.REASON_DETAIL IS '加扣分原因JSON数组';
COMMENT ON COLUMN PB_ASSESS_MONTH_RESULT.RULE_VERSION IS '模块计算规则版本';
